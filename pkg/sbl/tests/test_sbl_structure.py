"""Structural integrity tests for precompiled Snowball DSL (.sbl) files.

Validates that all 216 .sbl files exist, are non-empty, and conform to the expected
Snowball grammar structure without requiring any external compiler or binary dependencies.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from lemmajet import MODES, SIZES, SUPPORTED_LANGUAGES, VARIANTS

_SBL_ROOT = Path(__file__).resolve().parent.parent
_SAMPLE_SBL = _SBL_ROOT / "stemmer" / "pl" / "md_balanced.sbl"

if not _SAMPLE_SBL.is_file():
    pytest.skip(
        "Snowball artifacts not generated (run scripts/build_pkg.py first)",
        allow_module_level=True,
    )


@pytest.mark.parametrize("lang", SUPPORTED_LANGUAGES)
@pytest.mark.parametrize("mode", MODES)
@pytest.mark.parametrize("size", SIZES)
@pytest.mark.parametrize("variant", VARIANTS)
def test_sbl_file_structure(lang: str, mode: str, size: str, variant: str) -> None:
    """Validate structure of each generated .sbl file."""
    sbl_path = _SBL_ROOT / mode / lang / f"{size}_{variant}.sbl"
    assert sbl_path.is_file(), f"Missing Snowball file: {sbl_path}"
    assert sbl_path.stat().st_size > 0, f"Empty Snowball file: {sbl_path}"

    content = sbl_path.read_text(encoding="utf-8")

    # Header and model identity
    assert content.startswith(
        "/*\n============================================================================"
    )
    assert "Generated by LemmaJet (https://lemmajet.org/)" in content
    assert "Author     : Michal Šrajer" in content
    assert "Say thanks : https://buymeacoffee.com/lemmajet" in content
    assert "License    : MIT (Please retain this header)" in content
    expected_target_mode = "lemma" if mode == "lemmatizer" else "stem"
    if expected_target_mode == "lemma":
        assert "(lemma)" in content or "(mode:lemma" in content
    else:
        assert f"corpus:{lang}" in content

    # Key Snowball DSL sections
    assert "routines (" in content
    assert "externals (" in content
    assert "backwardmode (" in content
    assert "define stem as (" in content
    assert "define lemmatize as (" in content

    # Parentheses balance
    open_parens = content.count("(")
    close_parens = content.count(")")
    assert open_parens == close_parens, (
        f"Mismatched parentheses in {sbl_path}: {open_parens} '(' vs {close_parens} ')'"
    )
